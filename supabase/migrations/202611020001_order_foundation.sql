-- KENNIX order foundation
-- Safe to run once in Supabase SQL Editor. Does not expose customer orders publicly.

ALTER TABLE public.orders
  ADD COLUMN IF NOT EXISTS order_reference TEXT,
  ADD COLUMN IF NOT EXISTS payment_status TEXT NOT NULL DEFAULT 'pending',
  ADD COLUMN IF NOT EXISTS payment_provider TEXT,
  ADD COLUMN IF NOT EXISTS payment_reference TEXT,
  ADD COLUMN IF NOT EXISTS paid_at TIMESTAMPTZ;

CREATE UNIQUE INDEX IF NOT EXISTS orders_order_reference_uidx
  ON public.orders (order_reference)
  WHERE order_reference IS NOT NULL;

CREATE UNIQUE INDEX IF NOT EXISTS orders_payment_reference_uidx
  ON public.orders (payment_reference)
  WHERE payment_reference IS NOT NULL;

CREATE TABLE IF NOT EXISTS public.order_items (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id BIGINT NOT NULL REFERENCES public.orders(id) ON DELETE CASCADE,
  product_id BIGINT REFERENCES public.products(id) ON DELETE SET NULL,
  variant_id BIGINT REFERENCES public.product_variants(id) ON DELETE SET NULL,
  product_name TEXT NOT NULL,
  variant_label TEXT,
  quantity INTEGER NOT NULL CHECK (quantity > 0),
  unit_price NUMERIC(12,2) NOT NULL CHECK (unit_price >= 0),
  line_total NUMERIC(12,2) NOT NULL CHECK (line_total >= 0),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

ALTER TABLE public.order_items ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "KENNIX admin views order items" ON public.order_items;
CREATE POLICY "KENNIX admin views order items"
  ON public.order_items FOR SELECT TO authenticated
  USING ((auth.jwt() ->> 'email') = 'kennix2027@gmail.com');

DROP POLICY IF EXISTS "KENNIX admin manages order items" ON public.order_items;
CREATE POLICY "KENNIX admin manages order items"
  ON public.order_items FOR ALL TO authenticated
  USING ((auth.jwt() ->> 'email') = 'kennix2027@gmail.com')
  WITH CHECK ((auth.jwt() ->> 'email') = 'kennix2027@gmail.com');

-- No anon INSERT/SELECT/UPDATE policy is added.
-- Customer order creation and payment updates must happen through a trusted server function.
