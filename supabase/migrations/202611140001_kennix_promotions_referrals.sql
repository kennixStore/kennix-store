ALTER TABLE public.orders
  ADD COLUMN IF NOT EXISTS coupon_code TEXT,
  ADD COLUMN IF NOT EXISTS referral_code TEXT,
  ADD COLUMN IF NOT EXISTS coupon_discount NUMERIC(12,2) NOT NULL DEFAULT 0;

CREATE TABLE IF NOT EXISTS public.kennix_coupons (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code TEXT NOT NULL UNIQUE,
  discount_type TEXT NOT NULL CHECK (discount_type IN ('percent','fixed')),
  discount_value NUMERIC(12,2) NOT NULL CHECK (discount_value > 0),
  minimum_order NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (minimum_order >= 0),
  maximum_discount NUMERIC(12,2),
  usage_limit INTEGER,
  usage_count INTEGER NOT NULL DEFAULT 0,
  starts_at TIMESTAMPTZ,
  ends_at TIMESTAMPTZ,
  is_active BOOLEAN NOT NULL DEFAULT FALSE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CHECK (maximum_discount IS NULL OR maximum_discount > 0),
  CHECK (usage_limit IS NULL OR usage_limit > 0)
);

CREATE TABLE IF NOT EXISTS public.kennix_referral_codes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code TEXT NOT NULL UNIQUE,
  referrer_name TEXT,
  referrer_phone TEXT,
  reward_amount NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (reward_amount >= 0),
  is_active BOOLEAN NOT NULL DEFAULT FALSE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.kennix_referral_rewards (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  referral_code TEXT NOT NULL REFERENCES public.kennix_referral_codes(code),
  order_id BIGINT NOT NULL UNIQUE REFERENCES public.orders(id) ON DELETE CASCADE,
  reward_amount NUMERIC(12,2) NOT NULL CHECK (reward_amount >= 0),
  status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','approved','paid','void')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  paid_at TIMESTAMPTZ
);

ALTER TABLE public.kennix_coupons ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.kennix_referral_codes ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.kennix_referral_rewards ENABLE ROW LEVEL SECURITY;

